-- Esquema VetAndes. El usuario propietario de este esquema es VETANDES.
-- Incluye las tablas del anexo del examen y completa usuarios/roles/usuario_roles.

CREATE TABLE propietario (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR2(8) NOT NULL UNIQUE,
    nombres VARCHAR2(120) NOT NULL,
    telefono VARCHAR2(15)
);

CREATE TABLE prestacion (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(7) NOT NULL UNIQUE,
    nombre VARCHAR2(80) NOT NULL,
    precio NUMBER(10,2) NOT NULL CHECK (precio > 0),
    especie_aplicable VARCHAR2(6) NOT NULL
        CHECK (especie_aplicable IN ('PERRO', 'GATO', 'TODAS')),
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1))
);

CREATE TABLE mascota (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(40) NOT NULL,
    especie VARCHAR2(6) NOT NULL CHECK (especie IN ('PERRO', 'GATO', 'OTRO')),
    raza VARCHAR2(40),
    fecha_nacimiento DATE NOT NULL,
    sexo CHAR(1) NOT NULL CHECK (sexo IN ('M', 'H')),
    propietario_id NUMBER NOT NULL REFERENCES propietario(id),
    CONSTRAINT uq_mascota UNIQUE (nombre, propietario_id)
);

CREATE TABLE atencion (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR2(9) NOT NULL UNIQUE,
    fecha TIMESTAMP NOT NULL,
    mascota_id NUMBER NOT NULL REFERENCES mascota(id),
    peso NUMBER(5,2) NOT NULL CHECK (peso > 0),
    diagnostico VARCHAR2(300),
    estado VARCHAR2(12) NOT NULL CHECK (estado IN ('REGISTRADA', 'ANULADA')),
    subtotal NUMBER(10,2) NOT NULL,
    descuento NUMBER(10,2) NOT NULL,
    total NUMBER(10,2) NOT NULL,
    usuario_registro VARCHAR2(30) NOT NULL,
    motivo_anulacion VARCHAR2(200)
);

CREATE TABLE detalle_atencion (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atencion_id NUMBER NOT NULL REFERENCES atencion(id),
    prestacion_id NUMBER NOT NULL REFERENCES prestacion(id),
    cantidad NUMBER(1) NOT NULL CHECK (cantidad BETWEEN 1 AND 3),
    precio_unitario NUMBER(10,2) NOT NULL,
    subtotal NUMBER(10,2) NOT NULL,
    CONSTRAINT uq_detalle_atencion_prestacion UNIQUE (atencion_id, prestacion_id)
);

CREATE TABLE roles (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(30) NOT NULL UNIQUE
);

CREATE TABLE usuarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(30) NOT NULL UNIQUE,
    password VARCHAR2(100),
    nombre_completo VARCHAR2(120) NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1))
);

CREATE TABLE usuario_roles (
    usuario_id NUMBER NOT NULL REFERENCES usuarios(id),
    rol_id NUMBER NOT NULL REFERENCES roles(id),
    CONSTRAINT pk_usuario_roles PRIMARY KEY (usuario_id, rol_id)
);

CREATE SEQUENCE SEQ_ATENCION_NUMERO START WITH 5 INCREMENT BY 1 NOCACHE;

CREATE INDEX idx_mascota_propietario ON mascota(propietario_id);
CREATE INDEX idx_atencion_mascota_fecha ON atencion(mascota_id, fecha);
CREATE INDEX idx_atencion_estado_fecha ON atencion(estado, fecha);
CREATE INDEX idx_detalle_prestacion ON detalle_atencion(prestacion_id);

